package com.maxvibes.application.port.output

/**
 * Одно обращение агента к терминалу.
 *
 * Записывается в момент, когда команда предложена, а не когда выполнена:
 * вопрос, ради которого журнал существует, — к чему тянется модель, а не что
 * ей в итоге разрешили. Отклонённая команда для этого вопроса не менее
 * показательна, чем выполненная.
 *
 * [reason] необязателен, потому что необязателен в запросе команды: запись без
 * мотивировки — тоже наблюдение, и подменять её пустой строкой нельзя.
 */
data class TerminalUsageEntry(
    val sessionId: String,
    /** Режим взаимодействия, из которого пришла команда. */
    val provider: String,
    val command: String,
    val reason: String?
)

/**
 * Копит обращения к терминалу, чтобы по ним решать, какие средства плагина
 * стоит дописать.
 *
 * Терминал намеренно не запрещён: он остаётся выходом для того, чего плагин не
 * умеет. Но каждое обращение — заявка на недостающую возможность, и разбирать
 * эти заявки удобнее списком, а не выуживая из транскриптов диалогов.
 *
 * Реализация обязана быть безотказной: диагностика не имеет права помешать
 * выполнению команды, поэтому ошибки записи гасятся внутри.
 */
interface TerminalUsageLogPort {

    fun record(entry: TerminalUsageEntry)
}
