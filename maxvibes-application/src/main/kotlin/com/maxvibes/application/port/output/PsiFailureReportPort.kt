package com.maxvibes.application.port.output

/**
 * Отчёт об одном сбое на пути «ответ модели → изменённый код».
 *
 * Сбой разбора и сбой применения приходят из разных мест: первый — из адаптера
 * транспорта, где ещё жив сырой текст ответа, второй — из сервиса подтверждения,
 * где есть содержимое правок и ошибка PSI, но текста ответа уже нет. Поэтому
 * фиксированы только опознавательные поля, а содержимое лежит в [sections]:
 * каждая точка сбора кладёт то, что у неё действительно есть, вместо того чтобы
 * заполнять обязательные поля пустышками, неотличимыми от потерянных данных.
 */
data class PsiFailureReport(
    val kind: Kind,
    val sessionId: String,
    val provider: String,
    /** Одна строка для имени файла и первой строки отчёта. */
    val summary: String,
    val sections: List<Section>
) {

    enum class Kind {
        /** Запись в `modifications` не удалось разобрать — до PSI она не дошла. */
        PARSE,

        /** Запись разобрана, но PSI отказался её применить. */
        APPLY
    }

    data class Section(val title: String, val body: String)
}

/**
 * Складывает подробные отчёты о сбоях протокола правок отдельно от логов.
 *
 * Существует ради одного вопроса, на который лог диалога отвечает плохо: модель
 * прислала негодную правку или плагин не смог применить годную. Ответ требует
 * полного текста запроса, ответа и ошибки рядом, а не разбросанными по мегабайтам
 * транскрипта.
 *
 * Реализация обязана быть безотказной: диагностика не имеет права уронить работу,
 * поэтому ошибки записи гасятся внутри.
 */
interface PsiFailureReportPort {

    /** @return путь к созданному файлу или null, если записать не удалось. */
    fun report(report: PsiFailureReport): String?
}
